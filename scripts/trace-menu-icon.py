#!/usr/bin/env python3
"""Regenerate mac/Sources/OpenAGI/MenuBarIconGlyph.swift from the menu bar artwork.

The menu bar icon is drawn from vector paths at the menu bar's own backing
scale (MenuBarIcon.swift), so it is sharp at 1x, 2x and any scale. Those paths
are a potrace trace of the alpha channel of
mac/Resources/icon-sources/MenuIcon-source.png. Run this after changing that
artwork:

    uv run --with potracer --with pillow --with numpy scripts/trace-menu-icon.py

It prints how closely the trace matches the source (IoU) and rewrites the
generated Swift file.
"""
import os
import sys

import numpy as np
import potrace
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "mac/Resources/icon-sources/MenuIcon-source.png")
OUT = os.path.join(ROOT, "mac/Sources/OpenAGI/MenuBarIconGlyph.swift")


def trace(mask):
    plist = potrace.Bitmap(mask).trace(
        turdsize=20, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY,
        alphamax=1.0, opticurve=True, opttolerance=0.2)
    h, w = mask.shape
    curves = []
    for curve in plist:
        segs = curve.segments
        # potracer also returns the image frame as a 4-corner path; skip it.
        if len(segs) == 4 and all(s.is_corner for s in segs):
            xs = [s.end_point.x for s in segs] + [s.c.x for s in segs]
            if min(xs) <= 0 and max(xs) >= w:
                continue
        curves.append(curve)
    return curves


def flatten(curve, steps=24):
    cur = (curve.start_point.x, curve.start_point.y)
    pts = [cur]
    for s in curve.segments:
        if s.is_corner:
            pts += [(s.c.x, s.c.y), (s.end_point.x, s.end_point.y)]
        else:
            p0, p1, p2, p3 = cur, (s.c1.x, s.c1.y), (s.c2.x, s.c2.y), (s.end_point.x, s.end_point.y)
            for i in range(1, steps + 1):
                t = i / steps
                u = 1 - t
                pts.append(tuple(u**3 * p0[k] + 3 * u * u * t * p1[k] + 3 * u * t * t * p2[k] + t**3 * p3[k] for k in (0, 1)))
        cur = (s.end_point.x, s.end_point.y)
    return pts


def main():
    alpha = np.array(Image.open(SRC).convert("RGBA").split()[-1])
    mask = alpha >= 128
    curves = trace(mask)

    # Fidelity: rasterize the trace even-odd and compare with the source mask.
    acc = np.zeros(mask.shape, bool)
    allpts = []
    for curve in curves:
        pts = flatten(curve)
        allpts += pts
        im = Image.new("1", (mask.shape[1], mask.shape[0]), 0)
        ImageDraw.Draw(im).polygon(pts, fill=1)
        acc ^= np.array(im)
    iou = (acc & mask).sum() / (acc | mask).sum()
    print(f"trace vs source IoU: {iou:.4f}", file=sys.stderr)

    xs = [p[0] for p in allpts]
    ys = [p[1] for p in allpts]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)

    def f(v):
        return f"{v:.1f}"

    lines = []
    for curve in curves:
        lines.append(f"    .move({f(curve.start_point.x)}, {f(curve.start_point.y)}),")
        for s in curve.segments:
            if s.is_corner:
                lines.append(f"    .line({f(s.c.x)}, {f(s.c.y)}),")
                lines.append(f"    .line({f(s.end_point.x)}, {f(s.end_point.y)}),")
            else:
                lines.append(
                    f"    .curve({f(s.end_point.x)}, {f(s.end_point.y)}, "
                    f"{f(s.c1.x)}, {f(s.c1.y)}, {f(s.c2.x)}, {f(s.c2.y)}),")
        lines.append("    .close,")

    swift = f"""// Generated by scripts/trace-menu-icon.py from
// mac/Resources/icon-sources/MenuIcon-source.png. Do not edit by hand.
// Trace vs source IoU: {iou:.4f}.

import CoreGraphics

extension MenuBarIcon {{
  /// The glyph's extent, in source pixels (y down).
  static let glyphBounds = CGRect(x: {f(x0)}, y: {f(y0)}, width: {f(x1 - x0)}, height: {f(y1 - y0)})

  /// The glyph outline, in source pixels (y down). Filled even-odd: the
  /// head's inner contour cuts the ring, and the eyes sit inside it.
  static let glyphPath: [PathElement] = [
{chr(10).join(lines)}
  ]
}}
"""
    with open(OUT, "w") as fh:
        fh.write(swift)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(curves)} contours)", file=sys.stderr)


if __name__ == "__main__":
    main()
